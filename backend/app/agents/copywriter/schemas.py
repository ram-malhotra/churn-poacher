"""
Data schemas for the Copywriter Agent.
Covers executive emails, LinkedIn outreach sequences, technical migration pitches,
value proposition briefs, objection handling matrices, and evidence audit reports.
"""

from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class EmailVariant(BaseModel):
    """Structured email collateral variant tailored to specific executive personas."""
    variant_type: str = "EXECUTIVE_CONCISE"  # EXECUTIVE_CONCISE or TECHNICAL_COMMERCIAL
    target_role: str = "CTO / VP Engineering"  # e.g., "CTO / VP Engineering", "Head of Infrastructure / FinOps Lead"
    subject_lines: List[str] = Field(default_factory=list, description="3 subject lines with distinct hooks")
    preheader: str = ""
    body_markdown: str = ""
    call_to_action: str = ""
    referenced_attachments: List[str] = Field(default_factory=list)


class LinkedInSequence(BaseModel):
    """Multi-touch LinkedIn messaging sequence following peer-to-peer engineering tone."""
    step_1_connection_request: str = Field(..., max_length=300, description="Connection request strictly < 300 chars")
    step_2_value_add: str = Field(..., description="Post-connection architectural/benchmark context")
    step_3_technical_commercial: str = Field(..., description="Follow-up with financial savings delta and POC offer")


class TechnicalMigrationPitch(BaseModel):
    """Deep-dive technical migration brief for engineering leadership."""
    title: str = "OpenTelemetry Technical Migration Brief"
    target_audience: str = "Engineering Leadership"
    architecture_comparison: Dict[str, str] = Field(default_factory=dict)
    zero_code_migration_path: str = ""
    dual_shipping_poc: str = ""
    alert_and_dashboard_parity: str = ""
    timeline_and_effort: str = ""
    full_pitch_markdown: str = ""


class ValuePropositionSummary(BaseModel):
    """Structured 1-page financial business case and TCO analysis."""
    executive_summary: str = ""
    current_estimated_runrate_annual: float = 0.0
    target_alternative_runrate_annual: float = 0.0
    annual_savings_usd: float = 0.0
    savings_percentage: float = 0.0
    datadog_tax_breakdown: Dict[str, str] = Field(default_factory=dict)
    tco_payback_period_months: float = 0.0
    three_year_net_savings_usd: float = 0.0
    risk_vs_reward: List[Dict[str, str]] = Field(default_factory=list)
    full_value_prop_markdown: str = ""


class ObjectionItem(BaseModel):
    """Specific enterprise objection with counter-talking points and technical proof."""
    objection_id: str
    objection: str
    talking_points: List[str] = Field(default_factory=list)
    recommended_response: str
    technical_proof_point: str


class ObjectionHandlingMatrix(BaseModel):
    """Complete collection of enterprise objection responses."""
    items: List[ObjectionItem] = Field(default_factory=list)


class EvidenceClaim(BaseModel):
    """Claim extracted from generated collateral checked for factual backing."""
    claim_text: str
    claim_type: str  # FINANCIAL, INFRASTRUCTURE, VENDOR_USAGE, TIMELINE
    is_verified: bool
    source_reference: str


class EvidenceAuditReport(BaseModel):
    """Audit report validating factual grounding, compliance, and anti-hallucination."""
    passed: bool
    claims_checked: int
    verified_claims: int
    inferred_or_estimated_claims: int
    unsupported_claims_flagged: List[str] = Field(default_factory=list)
    buzzwords_detected: List[str] = Field(default_factory=list)
    hallucination_risk_score: float = Field(ge=0.0, le=1.0)
    audit_summary: str


class OutreachPackage(BaseModel):
    """Complete personalized competitive deposition pack generated by Copywriter Agent."""
    company_name: str
    company_id: str
    target_challenger: str = "SigNoz Cloud"
    distress_category: str = "BILLING_SHOCK"
    
    executive_emails: List[EmailVariant] = Field(default_factory=list)
    linkedin_sequence: LinkedInSequence
    technical_pitch: TechnicalMigrationPitch
    value_proposition: ValuePropositionSummary
    objection_matrix: ObjectionHandlingMatrix
    evidence_audit: EvidenceAuditReport
    
    generated_at: str
    governance_status: str = "DRAFT_PENDING_APPROVAL"  # Strictly requires human sign-off
